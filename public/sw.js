/**
 * Service worker minimal pentru Manager 24/7.
 * Ține doar coaja aplicației în cache, ca ecranul să pornească și pe o conexiune
 * proastă. Cererile către Supabase nu sunt puse niciodată în cache, ca datele
 * afișate să fie mereu cele reale.
 */
const CACHE = 'manager247-shell-v4';
const SHELL = ['/', '/manifest.webmanifest', '/icons/manager247-app-icon.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/auth')) return;

  // Navigările merg întâi în rețea, ca utilizatorul să primească versiunea nouă
  // imediat ce este publicată, și cad pe cache doar când nu există conexiune.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          void caches.open(CACHE).then((cache) => cache.put('/', copy));
          return response;
        })
        .catch(() => caches.match('/').then((cached) => cached ?? Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => cached ?? fetch(request).then((response) => {
      if (response.ok && response.type === 'basic') {
        const copy = response.clone();
        void caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })),
  );
});
